# CAREFLOW AI – CAPACITY SIMULATION

def simulate_capacity(
    data,
    staff_absences=None,
    unavailable_beds=None
):

    results = data.copy()

    if staff_absences is None:
        staff_absences = {}

    if unavailable_beds is None:
        unavailable_beds = {}

    results["Staff_Absences"] = results["Department"].map(
        staff_absences
    ).fillna(0).astype(int)

    results["Unavailable_Beds"] = results["Department"].map(
        unavailable_beds
    ).fillna(0).astype(int)

    results["Effective_Staff"] = (
        results["Available_Staff"] - results["Staff_Absences"]
    ).clip(lower=0)

    results["Usable_Beds"] = (
        results["Total_Beds"] - results["Unavailable_Beds"]
    ).clip(lower=0)

    results["Free_Beds"] = (
        results["Usable_Beds"] - results["Occupied_Beds"]
    ).clip(lower=0)

    results["Staff_Status"] = results.apply(
        lambda row: (
            "Understaffed"
            if row["Effective_Staff"] < row["Minimum_Staff"]
            else "Sufficient"
        ),
        axis=1
    )

    results["Capacity_Status"] = results.apply(
        lambda row: (
            "Over Capacity"
            if row["Occupied_Beds"] > row["Usable_Beds"]
            else "Available"
            if row["Free_Beds"] > 0
            else "Full"
        ),
        axis=1
    )

    return results

