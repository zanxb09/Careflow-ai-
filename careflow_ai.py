def simulate_capacity(data, staff_absences=None, unavailable_beds=None):
    results = data.copy()
    staff_absences = staff_absences or {}
    unavailable_beds = unavailable_beds or {}

    results["Effective_Staff"] = (
        results["Available_Staff"] -
        results["Department"].map(staff_absences).fillna(0)
    ).clip(lower=0)

    results["Usable_Beds"] = (
        results["Total_Beds"] -
        results["Department"].map(unavailable_beds).fillna(0)
    ).clip(lower=0)

    results["Free_Beds"] = (
        results["Usable_Beds"] - results["Occupied_Beds"]
    )

    results["Staff_Status"] = results.apply(
        lambda r: "Understaffed"
        if r["Effective_Staff"] < r["Minimum_Staff"]
        else "Sufficient", axis=1
    )

    results["Capacity_Status"] = results.apply(
        lambda r: "Over Capacity"
        if r["Occupied_Beds"] > r["Usable_Beds"]
        else "Full" if r["Free_Beds"] == 0 else "Available",
        axis=1
    )

    return results

