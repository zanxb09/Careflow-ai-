def integrate_hospital_data(
    process_data,
    staff_data,
    bed_data,
    handover_data
):
    integrated = process_data.copy()

    integrated = integrated.merge(
        staff_data,
        on="Department",
        how="left"
    )

    integrated = integrated.merge(
        bed_data,
        on="Department",
        how="left"
    )

    integrated = integrated.merge(
        handover_data[
            ["Department", "Information_Status"]
        ],
        on="Department",
        how="left"
    )

    integrated["Free_Beds"] = (
        integrated["Total_Beds"]
        - integrated["Occupied_Beds"]
    )

    integrated["Data_Quality"] = integrated.apply(
        lambda row: (
            "Incomplete"
            if row.isna().any()
            else "Complete"
        ),
        axis=1
    )

    return integrated


