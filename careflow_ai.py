def detect_bottlenecks(data):

    results = data.copy()

    def classify_waiting_time(row):

        if row["Status"] == "Completed":
            return "Completed"

        elif row["Waiting_Time_Min"] >= 90:
            return "Critical"

        elif row["Waiting_Time_Min"] >= 60:
            return "Warning"

        else:
            return "Normal"

    results["Bottleneck_Level"] = results.apply(
        classify_waiting_time, axis=1
    )

    bottlenecks = results[
        results["Bottleneck_Level"].isin(["Critical", "Warning"])
    ]

    bottlenecks = bottlenecks.sort_values(
        by="Waiting_Time_Min",
        ascending=False
    )

    return bottlenecks


