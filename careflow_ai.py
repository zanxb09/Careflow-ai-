def detect_bottlenecks(data):
    results = data.copy()

    def classify(row):
        if row["Status"] == "Completed":
            return "Completed"
        elif row["Waiting_Time_Min"] >= 90:
            return "Critical"
        elif row["Waiting_Time_Min"] >= 60:
            return "Warning"
        return "Normal"

    results["Bottleneck_Level"] = results.apply(classify, axis=1)

    return results[
        results["Bottleneck_Level"].isin(["Critical", "Warning"])
    ].sort_values("Waiting_Time_Min", ascending=False)

