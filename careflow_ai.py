def detect_missing_information(data):

    results = data.copy()

    required_fields = [
        "Previous_Examination",
        "Medication_Information",
        "Receiving_Department"
    ]

    results["Missing_Fields"] = results.apply(
        lambda row: [
            field for field in required_fields
            if pd.isna(row[field]) or str(row[field]).strip() == ""
        ],
        axis=1
    )

    results["Missing_Count"] = results["Missing_Fields"].apply(len)

    results["Information_Status"] = results["Missing_Count"].apply(
        lambda count: "Complete" if count == 0 else "Incomplete"
    )

    return results


